"""Scalar API Reference mount for FastAPI.

Replaces the default Swagger UI at /docs. Reads the OpenAPI schema generated by
FastAPI (via app.openapi_url) — no coupling to domain/application/infrastructure.

Activation is controlled by the SCALAR_DOCS_ENABLED env var (default: enabled).

Security posture: /docs is served from the same origin as the API, which is where
the HttpOnly refresh cookie lives and which OriginCheckMiddleware trusts via
``Sec-Fetch-Site: same-origin``. Any script this page loads therefore runs with the
API origin's privileges, so:

- the Scalar bundle is pinned to an exact version and file on jsdelivr and checked
  with Subresource Integrity (SRI), so a malicious or compromised republish cannot
  run in this origin;
- no third-party proxy is used: the page and /openapi.json are same-origin, so
  "Try it" calls the API directly;
- the auth token typed in the docs is not persisted (no ``persistAuth``), it only
  lives in memory;
- Agent Scalar ("Ask AI"), developer tools and telemetry are off, because they route
  through Scalar's services;
- the page is rendered and validated once at setup. If the template is not what we
  expect, /docs is not registered (the API stays up) and an error is logged;
- /docs carries its own CSP: only the pinned bundle and the hashed inline init script
  may run, and the page can only connect to this origin.
"""

from __future__ import annotations

import base64
import hashlib
import os
import re
from typing import Final

from fastapi import FastAPI
from fastapi.responses import HTMLResponse
from loguru import logger
from scalar_fastapi import AgentScalarConfig, Layout, Theme, get_scalar_api_reference

# To bump the version: set _SCALAR_VERSION to a release at least two weeks old,
# download the exact file at _SCALAR_JS_URL and recompute the hash:
#   curl -sSL <url> | openssl dgst -sha384 -binary | openssl base64 -A
# or, anywhere Python runs (works on Windows too; Get-FileHash prints hex, which
# would have to be converted to base64 for SRI):
#   python -c "import base64,hashlib,sys,urllib.request as u;print('sha384-'+base64.b64encode(hashlib.sha384(u.urlopen(sys.argv[1]).read()).digest()).decode())" <url>
# then set _SCALAR_JS_INTEGRITY to "sha384-<output>". Confirm the file path
# exists for that version (https://data.jsdelivr.com/v1/packages/npm/@scalar/api-reference@<version>).
_SCALAR_VERSION: Final[str] = "1.76.0"  # published 2026-10-23
_SCALAR_JS_URL: Final[str] = (
    f"https://cdn.jsdelivr.net/npm/@scalar/api-reference@{_SCALAR_VERSION}/dist/browser/standalone.js"
)
_SCALAR_JS_INTEGRITY: Final[str] = (
    "sha384-oH1C0RwqcwbVXkC+r8A+4qRoyEUQdtxAzOwumkxZtQBBcsy61FOoPt7B50OVJYYQ"
)
# Default favicon of scalar-fastapi, kept for visual parity; its origin is allowed in img-src.
_FAVICON_ORIGIN: Final[str] = "https://fastapi.tiangolo.com"
_FONTS_ORIGIN: Final[str] = "https://fonts.scalar.com"
_DEFAULT_THEME: Final[Theme] = Theme.KEPLER
_DEFAULT_LAYOUT: Final[Layout] = Layout.MODERN
_ENV_FLAG: Final[str] = "SCALAR_DOCS_ENABLED"


def is_scalar_docs_enabled() -> bool:
    """Return True if the SCALAR_DOCS_ENABLED env var is truthy (default: enabled)."""
    return os.getenv(_ENV_FLAG, "true").strip().lower() == "true"


_EXTERNAL_SCRIPT_RE: Final[re.Pattern[str]] = re.compile(r"<script\b[^>]*\bsrc\s*=", re.IGNORECASE)
_INLINE_SCRIPT_RE: Final[re.Pattern[str]] = re.compile(
    r"<script>(.*?)</script>", re.DOTALL | re.IGNORECASE
)
_ANY_SCRIPT_RE: Final[re.Pattern[str]] = re.compile(r"<script\b", re.IGNORECASE)


def _build_docs_page(page_html: str) -> tuple[str, str]:
    """Validate the rendered template, add SRI and return ``(html, csp)``.

    scalar-fastapi has no integrity parameter, so the tag it renders is rewritten.
    Raises ``ValueError`` if the template is not exactly what we expect (one external
    script, the pinned one, plus one inline init script): serving it could run
    unexpected code in the API origin.
    """
    plain_tag = f'<script src="{_SCALAR_JS_URL}"></script>'
    if len(_ANY_SCRIPT_RE.findall(page_html)) != 2:
        raise ValueError("expected exactly two script tags: the pinned bundle and the inline init")
    if len(_EXTERNAL_SCRIPT_RE.findall(page_html)) != 1 or page_html.count(plain_tag) != 1:
        raise ValueError(
            "expected exactly one external script and it must be the pinned Scalar bundle"
        )
    inline_scripts = _INLINE_SCRIPT_RE.findall(page_html)
    if len(inline_scripts) != 1 or "Scalar.createApiReference" not in inline_scripts[0]:
        raise ValueError(
            "expected exactly one inline script with the Scalar.createApiReference init"
        )

    sri_tag = f'<script src="{_SCALAR_JS_URL}" integrity="{_SCALAR_JS_INTEGRITY}" crossorigin="anonymous"></script>'
    inline_hash = base64.b64encode(
        hashlib.sha256(inline_scripts[0].encode("utf-8")).digest()
    ).decode()
    csp = "; ".join(
        [
            "default-src 'none'",
            f"script-src {_SCALAR_JS_URL} 'sha256-{inline_hash}'",
            "style-src 'unsafe-inline'",
            f"font-src {_FONTS_ORIGIN}",
            f"img-src 'self' data: blob: {_FAVICON_ORIGIN}",
            "connect-src 'self'",
            "object-src 'none'",
            "base-uri 'none'",
            "form-action 'none'",
            "frame-ancestors 'none'",
        ]
    )
    return page_html.replace(plain_tag, sri_tag), csp


def setup_scalar_docs(
    app: FastAPI,
    *,
    title: str,
    theme: Theme = _DEFAULT_THEME,
    layout: Layout = _DEFAULT_LAYOUT,
) -> bool:
    """Mount Scalar UI at /docs if enabled by env.

    Returns True if the endpoint was registered. Returns False when docs are disabled
    by env or when the rendered template fails validation (an error is logged).
    Idempotent at the FastAPI app level: re-registering the same path would 409.
    The API description lives in the OpenAPI schema at /openapi.json, which Scalar
    renders alongside the title.
    """
    if not is_scalar_docs_enabled():
        return False

    openapi_url = app.openapi_url or "/openapi.json"

    page = get_scalar_api_reference(
        openapi_url=openapi_url,
        title=title,
        scalar_js_url=_SCALAR_JS_URL,
        theme=theme,
        dark_mode=True,
        layout=layout,
        persist_auth=False,
        show_developer_tools="never",
        telemetry=False,
        agent=AgentScalarConfig(disabled=True),
    )
    try:
        html, csp = _build_docs_page(bytes(page.body).decode("utf-8"))
    except ValueError as exc:
        logger.error(f"Scalar docs not registered: {exc}")
        return False

    @app.get("/docs", include_in_schema=False)
    async def scalar_docs() -> HTMLResponse:
        return HTMLResponse(html, headers={"Content-Security-Policy": csp})

    return True
